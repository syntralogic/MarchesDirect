// Fiche marché (maquette v26, écran 3): pure rules, no network, no AI.
// Everything here is derived from the real match-score response and the visitor's answers.
import type { ApiMatchCriterion } from '@/lib/apiClient';

export type FicheQuestion = 'zone' | 'dispo' | 'moyens' | 'refs';
export type FicheAnswers = Partial<Record<FicheQuestion, 0 | 1>>;
export type ScoreTone = 'hi' | 'mid' | 'lo';

export const QUESTIONS: { key: FicheQuestion; text: string; criterion: ApiMatchCriterion['key']; engine: string }[] = [
  { key: 'zone', text: 'Intervenez-vous dans ce département ?', criterion: 'zone', engine: 'location' },
  { key: 'dispo', text: 'Pouvez-vous démarrer dans les délais indiqués ?', criterion: 'disponibilite', engine: 'calendar' },
  { key: 'moyens', text: 'Avez-vous l’équipe et le matériel pour plusieurs sites ?', criterion: 'moyens', engine: 'capacity' },
  { key: 'refs', text: 'Avez-vous 2 chantiers similaires à présenter ?', criterion: 'experience', engine: 'experience' },
];

// "location:oui,calendar:non" - the exact format the match-score endpoint whitelists.
export function answersToParam(a: FicheAnswers): string {
  return QUESTIONS.filter(q => a[q.key] !== undefined)
    .map(q => `${q.engine}:${a[q.key] === 1 ? 'oui' : 'non'}`).join(',');
}

export const scoreTone = (s: number): ScoreTone => (s >= 70 ? 'hi' : s >= 40 ? 'mid' : 'lo');
export const scoreLabel = (s: number) => (s >= 70 ? 'Très adapté' : s >= 40 ? 'À étudier' : 'Peu adapté');

export function summaryFor(s: number): string {
  if (s >= 70) return 'Votre activité correspond à ce que demande l’acheteur.';
  if (s >= 40) return 'Ce marché mérite d’être étudié : votre activité est proche de la demande, certains points restent à confirmer.';
  return 'Ce marché est éloigné de votre activité. D’autres marchés vous correspondent mieux.';
}

// Short, faithful title: official title kept in "Le marché en détail". 60 characters at a word boundary.
export function shortTitle(official: string, city?: string | null): string {
  const clean = official.replace(/\s+/g, ' ').trim();
  let t = clean;
  if (clean.length > 60) {
    const cut = clean.slice(0, 60);
    t = cut.slice(0, Math.max(cut.lastIndexOf(' '), 30)).replace(/[\s,;:–-]+$/, '') + '…';
  }
  const c = (city || '').trim();
  if (c && !clean.toLowerCase().includes(c.toLowerCase()) && t.length + c.length + 3 <= 80) t = `${t} — ${c}`;
  return t;
}

// Whole calendar days left (Europe/Paris), negative when the deadline has passed.
export function daysLeft(deadline: string | null | undefined, now: Date = new Date()): number | null {
  if (!deadline) return null;
  const d = new Date(deadline);
  if (Number.isNaN(d.getTime())) return null;
  const day = (x: Date) => {
    const p = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Paris', year: 'numeric', month: '2-digit', day: '2-digit' }).format(x);
    return Date.UTC(+p.slice(0, 4), +p.slice(5, 7) - 1, +p.slice(8, 10)) / 86400000;
  };
  return Math.round(day(d) - day(now));
}

const Q_LABEL: Record<FicheQuestion, string> = {
  zone: 'votre zone d’intervention',
  refs: 'vos références sur des prestations similaires',
  dispo: 'votre disponibilité dans les délais',
  moyens: 'vos moyens pour plusieurs sites',
};
const NO_TEXT: Record<FicheQuestion, string> = {
  zone: 'Le lieu d’exécution est en dehors de votre zone d’intervention.',
  refs: 'Vous n’avez pas encore de référence similaire à présenter.',
  dispo: 'Les délais ne vous conviennent pas.',
  moyens: 'Vos moyens ne couvrent pas plusieurs sites.',
};
const ORDER: FicheQuestion[] = ['zone', 'refs', 'dispo', 'moyens'];
const cap = (t: string) => t.charAt(0).toUpperCase() + t.slice(1);
const joinFr = (a: string[]) => (a.length <= 1 ? a.join('') : `${a.slice(0, -1).join(', ')} et ${a[a.length - 1]}`);

export interface AdviceInput {
  score: number;
  activity: 'match' | 'confirm' | 'mismatch';
  nature: string;   // e.g. "de climatisation"
  city: string;
  company: string;
  answers: FicheAnswers;
}

// Three sentences, generated by rules (never by AI on page load).
// A "Non" on the zone never changes sentence 1: the trade is not called into question.
export function buildAdvice(i: AdviceInput): { text: string; suggestBetter: boolean } {
  const tbc = ORDER.filter(k => i.answers[k] === undefined);
  const no = ORDER.filter(k => i.answers[k] === 0);
  const where = i.city ? ` à ${i.city}` : '';
  const a = i.activity === 'match'
    ? `Ce marché ${i.nature}${where} est en lien direct avec l’activité de ${i.company}.`
    : i.activity === 'confirm'
      ? `Ce marché ${i.nature}${where} est proche de l’activité de ${i.company}, sans y correspondre entièrement.`
      : `Ce marché ${i.nature}${where} s’éloigne de l’activité de ${i.company}.`;
  let b: string;
  if (no.length) {
    b = no.slice(0, 2).map(k => NO_TEXT[k]).join(' ') + (no.length > 2 ? ' D’autres points ne correspondent pas.' : '') + (i.score >= 40 ? ' C’est le principal point à voir ensemble.' : '');
  } else if (tbc.length) {
    b = `${cap(joinFr(tbc.slice(0, 2).map(k => Q_LABEL[k])))}${tbc.length > 1 ? ' restent' : ' reste'} à préciser.`;
  } else {
    b = 'Vos réponses confirment les points clés : zone, délais, moyens et références.';
  }
  const c = i.score >= 70
    ? 'Votre dossier prérempli vous donne une première base pour avancer avec notre équipe.'
    : i.score >= 40
      ? (tbc.length ? 'Vos réponses nous aideront à préciser si ce marché convient à votre entreprise.' : 'Un échange avec notre équipe vous dira rapidement si ce marché vaut le coup d’être préparé.')
      : 'D’autres marchés de votre liste vous correspondent mieux : nous vous conseillons de commencer par eux.';
  return { text: `${a} ${b} ${c}`, suggestBetter: i.score < 40 };
}

export type CriterionStatus = 'ok' | 'tbc' | 'no' | 'unknown';
export const CRITERIA_ORDER: { key: ApiMatchCriterion['key']; label: string }[] = [
  { key: 'metier', label: 'Activité' },
  { key: 'zone', label: 'Zone d’intervention' },
  { key: 'disponibilite', label: 'Calendrier' },
  { key: 'moyens', label: 'Moyens' },
  { key: 'experience', label: 'Références' },
  { key: 'qualifications', label: 'Qualifications' },
];

// An unknown datum is NEVER shown as "Correspond".
export function criterionStatus(c: ApiMatchCriterion | undefined): CriterionStatus {
  if (!c) return 'unknown';
  if (c.status === 'mismatch') return 'no';
  if (c.status === 'match' && c.evidence !== 'unknown') return 'ok';
  return c.evidence === 'unknown' ? 'unknown' : 'tbc';
}
export const STATUS_TEXT: Record<CriterionStatus, string> = { ok: 'Correspond', tbc: 'À confirmer', no: 'Ne correspond pas', unknown: 'Non précisé' };
